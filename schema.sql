-- 1. Buat Tabel Akun (Accounts Table)
create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  code text unique not null,
  title text not null,
  th integer not null,
  status text not null default 'ready' check (status in ('ready', 'sold', 'booked')),
  price bigint not null,
  original_price bigint not null,
  image text not null,
  bk integer default 0,
  aq integer default 0,
  gw integer default 0,
  rc integer default 0,
  gems text default '1.000',
  cwl_medals text default '500',
  change_name text default 'Gratis (Free)',
  scid_status text default 'Clean Email (Supercell ID)',
  trophies text default '3.000',
  equipment text default 'Hero Equipment Lengkap',
  pets text default 'Battle Pets Siap',
  description text default '',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Aktifkan Row Level Security (RLS)
alter table public.accounts enable row level security;

-- 3. Kebijakan Keamanan (Security Policies):
-- Guest / Customer hanya bisa MELIHAT akun (SELECT)
drop policy if exists "Public can view accounts" on public.accounts;
create policy "Public can view accounts"
  on public.accounts for select
  using (true);

-- Hanya Admin yang sudah login (Authenticated) yang bisa Tambah, Edit, dan Hapus akun
drop policy if exists "Authenticated users can insert" on public.accounts;
create policy "Authenticated users can insert"
  on public.accounts for insert
  with check (auth.role() = 'authenticated');

drop policy if exists "Authenticated users can update" on public.accounts;
create policy "Authenticated users can update"
  on public.accounts for update
  using (auth.role() = 'authenticated');

drop policy if exists "Authenticated users can delete" on public.accounts;
create policy "Authenticated users can delete"
  on public.accounts for delete
  using (auth.role() = 'authenticated');

